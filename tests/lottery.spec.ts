import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
const people = Array.from({ length: 25 }, (_, index) => ({ id: index + 1, firstName: index === 0 ? 'Emily' : `User${index + 1}`, lastName: 'Johnson', username: index === 0 ? 'emilys' : `user${index + 1}`, email: `user${index + 1}@example.com`, age: 29, gender: 'female', phone: '+380501234567' }))
async function fakeApi(page: Page) {
  await page.route('https://dummyjson.com/**', async route => {
    const url = new URL(route.request().url()), method = route.request().method(), body = route.request().postDataJSON()
    const reply = (data: unknown, status = 200) => route.fulfill({ status, json: data })
    if (url.pathname === '/auth/login') return body.username === 'emilys' && body.password === 'emilyspass' ? reply({ ...people[0], accessToken: 'access', refreshToken: 'refresh' }) : reply({ message: 'Invalid credentials' }, 401)
    if (url.pathname === '/auth/me') return ['Bearer access', 'Bearer renewed'].includes(route.request().headers().authorization) ? reply(people[0]) : reply({ message: 'Expired' }, 401)
    if (url.pathname === '/auth/refresh') return body.refreshToken === 'refresh' ? reply({ accessToken: 'renewed', refreshToken: 'refresh' }) : reply({ message: 'Invalid refresh' }, 401)
    if (url.pathname === '/users/add') return reply({ ...body, id: 26 })
    if (/^\/users\/\d+$/.test(url.pathname)) {
      const id = Number(url.pathname.split('/').pop()), person = people.find(item => item.id === id)
      if (!person) return reply({ message: 'Not found' }, 404)
      return reply(method === 'PUT' ? { ...person, ...body } : person)
    }
    const q = url.searchParams.get('q')?.toLowerCase() || '', limit = Number(url.searchParams.get('limit') ?? 10), skip = Number(url.searchParams.get('skip') || 0)
    const selected = people.filter(person => `${person.firstName} ${person.lastName}`.toLowerCase().includes(q))
    return reply({ users: selected.slice(skip, limit ? skip + limit : undefined), total: selected.length, limit, skip })
  })
}
async function login(page: Page) {
  await page.locator('#login-username').fill('emilys'); await page.locator('#login-password').fill('emilyspass')
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await page.waitForURL(/#\/users/)
}
test.beforeEach(async ({ page }) => { await fakeApi(page) })

test('original Home registration, winners and persisted theme', async ({ page }) => {
  await page.goto('./')
  await page.getByLabel('Name', { exact: true }).fill('Student Example')
  await page.getByLabel('Date of Birth', { exact: true }).fill('2005-01-01')
  await page.getByLabel('Email', { exact: true }).fill('student@example.com')
  await page.getByLabel('Phone number', { exact: true }).fill('+380501234567')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Student Example' })).toBeVisible()
  await page.getByRole('button', { name: 'New winner', exact: true }).click()
  await expect(page.getByRole('button', { name: 'New winner', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Перемкнути тему', exact: true }).click()
  await expect(page.locator('html')).toHaveClass('dark')
  await page.reload(); await expect(page.locator('html')).toHaveClass('dark')
  await expect(page.getByRole('row').filter({ hasText: 'Student Example' })).toBeVisible()
  await page.getByRole('button', { name: 'Перемкнути тему', exact: true }).click()
  await expect(page.locator('html')).not.toHaveClass('dark')
})

